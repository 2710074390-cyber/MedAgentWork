def add(module, module_name, topic, qtype, polarity, bloom, stem, options, answer,
        explanation, source_page, difficulty, kaoyan_origin=None):
    key = (module, qtype)
    counters[key] = counters.get(key, 0) + 1
    seq = f"{counters[key]:03d}"
    qid = f"batch033-{module}-{qtype}-{seq}"
    # options: list of (label, text) OR list of text (auto A-E)
    opts = []
    for i, o in enumerate(options):
        if isinstance(o, tuple) or isinstance(o, list):
            lbl, txt = o[0], o[1]
        else:
            lbl, txt = chr(ord('A') + i), o
        opts.append({"label": lbl, "text": txt})
    pol = {}
    for o in opts:
        pol[o["label"]] = (o["label"] in answer)
    d = {
        "id": qid,
        "module": module,
        "module_name": module_name,
        "topic": topic,
        "type": qtype,
        "polarity": polarity,
        "bloom": bloom,
        "stem": stem,
        "options": opts,
        "answer": answer,
        "explanation": explanation,
        "source_page": source_page,
        "difficulty": difficulty,
        "option_polarities": pol,
    }
    if kaoyan_origin is not None:
        d["kaoyan_origin"] = kaoyan_origin
    questions.append(d)
    return d

